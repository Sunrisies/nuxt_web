const fs = require('node:fs')
const assert = require('node:assert/strict')
const root = '/Users/zhuzhongqian/Desktop/project/local-acceptance'
const { chromium } = require(root + '/.tools/node_modules/playwright-core')
const env = Object.fromEntries(fs.readFileSync(root + '/.env', 'utf8').split('\n').filter(l => l.includes('=')).map(l => { const i = l.indexOf('='); return [l.slice(0, i), l.slice(i + 1)] }))
const base = 'http://127.0.0.1:39158'
;(async () => {
  const browser = await chromium.launch({ executablePath: '/Applications/Google Chrome.app/Contents/MacOS/Google Chrome', headless: true })
  const context = await browser.newContext({ viewport: { width: 1440, height: 1000 } })
  const page = await context.newPage()
  const errors = [], checks = []
  let uuid, image, coverImage
  const api = (path, method = 'GET') => context.request.fetch(base + '/api/v1' + path, { method })
  page.on('pageerror', e => errors.push(e.message))
  try {
    await page.goto(base + '/admin/login')
    await page.getByPlaceholder('请输入账号').fill('local_admin')
    await page.getByPlaceholder('请输入密码').fill(env.LOCAL_ADMIN_PASSWORD)
    await page.getByRole('button', { name: '登录', exact: true }).click()
    await page.waitForURL('**/admin/dashboard')
    await page.goto(base + '/admin/posts')
    await page.getByRole('button', { name: '新建文章', exact: true }).click()
    await page.waitForURL('**/admin/posts/new')
    const title = '独立编辑器验收 ' + Date.now()
    await page.getByRole('textbox', { name: '文章标题', exact: true }).fill(title)
    await page.getByRole('textbox', { name: '文章正文', exact: true }).fill('# 独立编辑器\n\n草稿恢复及发布验收。')
    assert.equal(await page.getByRole('dialog').count(), 0)
    checks.push('独立新建页面')
    page.once('dialog', d => d.dismiss())
    await page.getByRole('link', { name: '返回文章列表', exact: true }).click()
    assert(page.url().endsWith('/new'))
    checks.push('未保存离开拦截')
    page.once('dialog', d => d.accept())
    await page.reload()
    await page.getByRole('button', { name: '恢复草稿', exact: true }).click()
    assert.equal(await page.getByRole('textbox', { name: '文章标题', exact: true }).inputValue(), title)
    checks.push('刷新草稿恢复')
    await page.getByRole('button', { name: '文章设置', exact: true }).click()
    await page.getByRole('dialog', { name: '文章设置', exact: true }).waitFor()
    const categories = (await (await api('/categories?limit=100')).json()).data.data
    const tags = (await (await api('/tags?limit=100')).json()).data.data
    for (const [label, name] of [['文章分类', categories[0].name], ['文章标签', tags[0].name]]) {
      await page.getByRole('combobox', { name: label, exact: true }).click()
      await page.getByRole('option', { name, exact: true }).click()
      if (await page.getByRole('listbox').isVisible()) await page.keyboard.press('Escape')
    }
    await page.getByRole('button', { name: '完成设置', exact: true }).click()
    page.once('dialog', d => d.accept())
    await page.reload()
    await page.getByRole('button', { name: '恢复草稿', exact: true }).click()
    assert.equal(await page.getByRole('textbox', { name: '文章标题', exact: true }).inputValue(), title)
    await page.getByRole('button', { name: '文章设置', exact: true }).click()
    await page.getByRole('combobox', { name: '文章分类', exact: true }).filter({ hasText: categories[0].name }).waitFor()
    await page.waitForFunction(() => [...document.images].some(i => i.alt === '封面预览' && i.complete && i.naturalWidth > 0))
    assert((await page.getByAltText('封面预览').getAttribute('src')).includes('/api/v1/posts/category-cover/'))
    await page.getByRole('button', { name: '完成设置', exact: true }).click()
    checks.push('设置弹窗与分类标签草稿恢复及后端默认封面')
    const upload = page.waitForResponse(r => r.request().method() === 'POST' && r.url().endsWith('/images/upload'))
    await page.locator('input[aria-label="上传正文图片文件"]').setInputFiles({ name: 'editor-page-test.png', mimeType: 'image/png', buffer: fs.readFileSync(root + '/results/authoring-fixture.png') })
    image = (await (await upload).json()).data
    await page.waitForFunction(url => document.querySelector('textarea[aria-label="文章正文"]').value.includes(url), image.url)
    await page.locator('[aria-label="正文预览"]').getByRole('heading', { name: '独立编辑器', exact: true }).waitFor()
    const left = await page.locator('[aria-label="Markdown 编辑区"]').boundingBox()
    const right = await page.locator('[aria-label="正文预览"]').boundingBox()
    assert(right.x > left.x && Math.abs(right.y - left.y) < 2)
    checks.push('左侧编辑右侧默认实时预览')
    await page.locator('[aria-label="正文预览"]').waitFor()
    checks.push('图片插入及正文预览')
    await page.route('**/api/v1/posts', route => route.request().method() === 'POST' ? route.fulfill({ status: 503, contentType: 'application/json', body: JSON.stringify({ code: 503, message: '模拟保存失败' }) }) : route.continue())
    await page.getByRole('button', { name: '保存草稿', exact: true }).click()
    await page.getByText('模拟保存失败', { exact: true }).first().waitFor()
    assert.equal(await page.getByRole('textbox', { name: '文章标题', exact: true }).inputValue(), title)
    await page.unroute('**/api/v1/posts')
    checks.push('保存失败保留输入')
    const created = page.waitForResponse(r => r.request().method() === 'POST' && r.url().endsWith('/posts'))
    await page.getByRole('button', { name: '保存草稿', exact: true }).click()
    uuid = (await (await created).json()).data.uuid
    await page.waitForURL('**/admin/posts/' + uuid + '/edit')
    await page.getByRole('button', { name: '保存', exact: true }).waitFor()
    assert.equal((await fetch(base + '/api/public/articles/' + uuid)).status, 404)
    const detail = (await (await api('/posts/' + uuid)).json()).data
    assert.equal(detail.cover, '/api/v1/posts/category-cover/' + categories[0].id + '.svg')
    checks.push('保存草稿后继续编辑且不公开')
    await page.getByRole('button', { name: '发布文章', exact: true }).click()
    await page.getByRole('link', { name: '查看文章', exact: true }).waitFor()
    assert.equal((await fetch(base + '/api/public/articles/' + uuid)).status, 200)
    checks.push('发布前台可见')
    await page.getByRole('textbox', { name: '文章正文', exact: true }).fill('# 修改后的正文\n\n保持编辑页面。')
    const saved = page.waitForResponse(r => r.request().method() === 'PUT' && r.url().endsWith('/posts/' + uuid))
    await page.getByRole('button', { name: '保存', exact: true }).click()
    assert.equal((await saved).status(), 200)
    await page.waitForFunction(() => !document.body.textContent.includes('有未保存的修改'))
    assert(page.url().endsWith('/edit'))
    checks.push('更新后继续编辑')
    await page.getByRole('button', { name: '文章设置', exact: true }).click()
    const coverUpload = page.waitForResponse(r => r.request().method() === 'POST' && r.url().endsWith('/images/upload'))
    await page.locator('input[aria-label="上传封面文件"]').setInputFiles({ name: 'editor-cover-test.png', mimeType: 'image/png', buffer: fs.readFileSync(root + '/results/authoring-fixture.png') })
    coverImage = (await (await coverUpload).json()).data
    await page.getByRole('button', { name: '使用分类默认封面', exact: true }).waitFor()
    await page.getByRole('button', { name: '完成设置', exact: true }).click()
    let coverSaved = page.waitForResponse(r => r.request().method() === 'PUT' && r.url().endsWith('/posts/' + uuid))
    await page.getByRole('button', { name: '保存', exact: true }).click()
    await coverSaved
    assert.equal((await (await api('/posts/' + uuid)).json()).data.cover, coverImage.url)
    assert.equal((await api('/images/' + coverImage.id, 'DELETE')).status(), 409)
    await page.getByRole('button', { name: '文章设置', exact: true }).click()
    await page.getByRole('button', { name: '使用分类默认封面', exact: true }).click()
    await page.getByRole('button', { name: '完成设置', exact: true }).click()
    coverSaved = page.waitForResponse(r => r.request().method() === 'PUT' && r.url().endsWith('/posts/' + uuid))
    await page.getByRole('button', { name: '保存', exact: true }).click()
    await coverSaved
    assert.equal((await (await api('/posts/' + uuid)).json()).data.cover, '/api/v1/posts/category-cover/' + categories[0].id + '.svg')
    checks.push('上传封面优先、引用保护及恢复分类默认封面')
    await page.getByRole('textbox', { name: '文章正文', exact: true }).fill('# 修改后的正文\n\n' + '长正文滚动验收。\n\n'.repeat(150))
    for (const width of [390, 768, 1440]) {
      await page.setViewportSize({ width, height: 900 })
      await page.waitForTimeout(400)
      if (width < 768) {
        await page.getByRole('button', { name: '预览正文', exact: true }).click()
        await page.locator('[aria-label="正文预览"]').getByRole('heading', { name: '修改后的正文', exact: true }).waitFor()
        await page.getByRole('button', { name: '编写内容', exact: true }).click()
      }
      assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth + 1), false)
      assert.equal(await page.evaluate(() => document.documentElement.scrollHeight > innerHeight + 1), false)
      const editor = page.getByRole('textbox', { name: '文章正文', exact: true })
      assert(await editor.evaluate(el => el.scrollHeight > el.clientHeight + 10))
      await editor.evaluate(el => { el.scrollTop = 400 })
      assert(await editor.evaluate(el => el.scrollTop > 0))
      if (width >= 768) {
        await page.locator('[data-testid="preview-scroll"]').evaluate(el => { el.scrollTop = 350 })
        assert(await page.locator('[data-testid="preview-scroll"]').evaluate(el => el.scrollTop > 0))
      }
      await page.getByRole('button', { name: '保存', exact: true }).scrollIntoViewIfNeeded()
      await page.screenshot({ path: root + '/results/article-editor-page-' + width + '.png', fullPage: true })
    }
    checks.push('手机平板电脑无横向溢出')
    page.once('dialog', d => d.accept())
    await page.goto(base + '/admin/posts?edit=' + uuid)
    await page.waitForURL('**/admin/posts/' + uuid + '/edit')
    checks.push('历史编辑链接兼容')
    assert.deepEqual(errors, [])
    console.log(JSON.stringify({ checks, errors }, null, 2))
  } finally {
    if (uuid) await api('/posts/' + uuid, 'DELETE')
    if (image) await api('/images/' + image.id, 'DELETE')
    if (coverImage) await api('/images/' + coverImage.id, 'DELETE')
    await browser.close()
  }
})().catch(e => { console.error(e); process.exitCode = 1 })
