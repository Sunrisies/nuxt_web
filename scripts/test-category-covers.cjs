const fs = require('node:fs')
const assert = require('node:assert/strict')
const root = '/Users/zhuzhongqian/Desktop/project/local-acceptance'
const { request } = require(root + '/.tools/node_modules/playwright-core')
const env = Object.fromEntries(fs.readFileSync(root + '/.env', 'utf8').split('\n').filter(l => l.includes('=')).map(l => { const i = l.indexOf('='); return [l.slice(0, i), l.slice(i + 1)] }))
;(async () => {
  const api = await request.newContext({ baseURL: 'http://127.0.0.1:39158' })
  const categories = [], stamp = Date.now()
  let uuid
  try {
    assert.equal((await api.post('/api/v1/auth/login', { data: { login_type: 'password', account: 'local_admin', password: env.LOCAL_ADMIN_PASSWORD } })).status(), 200)
    for (const name of ['默认封面甲', '默认封面乙']) {
      const response = await api.post('/api/v1/categories', { data: { name: name + stamp } })
      assert.equal(response.status(), 200)
      categories.push((await response.json()).data)
    }
    const tags = (await (await api.get('/api/v1/tags?limit=100')).json()).data.data
    const created = await api.post('/api/v1/posts', { data: { title: '分类封面验收' + stamp, markdowncontent: '# 默认封面\n\n分类默认封面验收正文。', content: '', category_id: categories[0].id, tag_ids: [tags[0].id], status: 1, featured: false } })
    assert.equal(created.status(), 200)
    const post = (await created.json()).data
    uuid = post.uuid
    assert.equal(post.cover, '/api/v1/posts/category-cover/' + categories[0].id + '.svg')
    let svg = await fetch('http://127.0.0.1:39158' + post.cover)
    assert.equal(svg.status, 200)
    assert(svg.headers.get('content-type').startsWith('image/svg+xml'))
    assert.equal(svg.headers.get('x-content-type-options'), 'nosniff')
    assert((await svg.text()).includes(categories[0].name))
    const updated = await api.put('/api/v1/posts/' + uuid, { data: { category_id: categories[1].id } })
    assert.equal(updated.status(), 200)
    const cover = (await updated.json()).data.cover
    assert.equal(cover, '/api/v1/posts/category-cover/' + categories[1].id + '.svg')
    svg = await fetch('http://127.0.0.1:39158' + cover)
    assert((await svg.text()).includes(categories[1].name))
    const detail = (await (await api.get('/api/v1/posts/' + uuid)).json()).data
    assert.equal(detail.cover, cover)
    const list = (await (await api.get('/api/v1/posts?search=' + encodeURIComponent('分类封面验收' + stamp))).json()).data.data
    assert.equal(list[0].cover, cover)
    console.log('Passed: missing cover generated by backend, anonymous SVG, category text, category change, create/update/detail/list consistency')
  } finally {
    if (uuid) await api.delete('/api/v1/posts/' + uuid)
    for (const category of categories) await api.delete('/api/v1/categories/' + category.id)
    await api.dispose()
  }
})().catch(error => { console.error(error); process.exitCode = 1 })
